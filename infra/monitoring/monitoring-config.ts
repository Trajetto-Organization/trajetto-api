function renderRuleGroup(
  name: string,
  comment: readonly string[],
  rules: readonly AlertRule[],
): string {
  const body = rules.map((rule) =>
    [
      `- alert: ${rule.alert}`,
      "  expr: |-",
      indent(rule.expr, 4),
      `  for: ${rule.for}`,
      "  labels:",
      `    severity: ${rule.severity}`,
      `    source: ${rule.source}`,
      "  annotations:",
      `    summary: ${quote(rule.summary)}`,
      `    runbook: ${quote(rule.runbook)}`,
    ].join("\n"),
  );

  return [
    `# ${GENERATED}`,
    ...comment.map((line) => `# ${line}`),
    "groups:",
    `  - name: ${name}`,
    "    interval: 1m",
    "    rules:",
    indent(body.join("\n"), 6),
    "",
  ].join("\n");
}

