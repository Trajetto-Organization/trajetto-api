function templating(byApplication: boolean): unknown {
  const environment = {
    name: "env",
    label: "Ambiente",
    type: "query",
    datasource: DATASOURCE,
    definition: "label_values(trajetto_build_info, env)",
    query: {
      query: "label_values(trajetto_build_info, env)",
      refId: "env",
    },
    refresh: 2,
    includeAll: false,
    multi: false,
    sort: 1,
  };
  const application = {
    name: "job",
    label: "Application",
    type: "query",
    datasource: DATASOURCE,
    definition: 'label_values(trajetto_build_info{env="$env"}, job)',
    query: {
      query: 'label_values(trajetto_build_info{env="$env"}, job)',
      refId: "job",
    },
    refresh: 2,
    includeAll: true,
    allValue: ".+",
    multi: true,
    sort: 1,
  };

  return { list: byApplication ? [environment, application] : [environment] };
}

function renderDashboard(dashboard: Dashboard): string {
  let x = 0;
  let y = 0;
  const height = 8;

  const panels = dashboard.panels.map((panel, index) => {
    if (x + panel.width > 24) {
      x = 0;
      y += height;
    }

    const gridPos = { h: height, w: panel.width, x, y };

    x += panel.width;

    return {
      id: index + 1,
      type: panel.type,
      title: panel.title,
      ...(panel.description ? { description: panel.description } : {}),
      datasource: DATASOURCE,
      gridPos,
      fieldConfig: { defaults: { unit: panel.unit }, overrides: [] },
      ...(panel.type === "timeseries"
        ? {
            options: {
              legend: {
                displayMode: "table",
                placement: "bottom",
                calcs: ["lastNotNull", "max"],
              },
            },
          }
        : {}),
      targets: panel.targets.map((target, at) => ({
        refId: String.fromCharCode(65 + at),
        datasource: DATASOURCE,
        expr: target.expr,
        legendFormat: target.legend,
        ...(panel.type === "table" ? { format: "table", instant: true } : {}),
      })),
    };
  });

  return `${JSON.stringify(
    {
      uid: dashboard.uid,
      title: dashboard.title,
      description: `${dashboard.description} ${DASHBOARD_ORIGIN}`,
      tags: ["trajetto"],
      timezone: "browser",
      editable: false,
      schemaVersion: 39,
      version: 1,
      refresh: "1m",
      time: { from: "now-6h", to: "now" },
      templating: templating(dashboard.byApplication),
      panels,
    },
    null,
    2,
  )}\n`;
}

