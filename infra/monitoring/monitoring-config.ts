interface AlertRule {
  alert: string;
  expr: string;
  for: string;
  severity: "page" | "warn";
  source: "ops-heartbeat" | "metrics";
  summary: string;
  /** A path in this repository: a runbook, or a section of the guide. */
  runbook: string;
}

/** `outbox-lag` → `TrajettoOutboxLag`. */
function alertName(code: string): string {
  return `Trajetto${code
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")}`;
}

/** The title of a runbook, from its first line: `# <code> — <title>`. */
function runbookTitle(code: AlertKind): string {
  const first = readFileSync(resolve(ROOT, runbookPath(code)), "utf8")
    .replace(/\r\n/g, "\n")
    .split("\n")[0];
  const match = /^# \S+ — (.+)$/.exec(first);

  if (!match) {
    throw new Error(
      `${runbookPath(code)}: a primeira linha não é "# ${code} — <título>"`,
    );
  }

  return match[1].trim();
}

/**
 * Seconds after which a verdict no longer counts: the heartbeat runs every
 * minute, so five minutes without one is a stopped heartbeat (its own rule),
 * not a reason to keep paging on what it said last.
 */
const VERDICT_FRESH_SECONDS = 300;

/**
 * The newest verdict of the environment, for one code. Only the process
 * that won the minute's heartbeat updates `trajetto_alert_active`; the one
 * that won a minute ago still shows what it judged then. So the series
 * counts only on the instance with the newest evaluation of its
 * environment, and only while that evaluation is fresh.
 */
function verdictExpr(selector: string): string {
  return [
    "max by (env, code) (",
    `  trajetto_alert_active${selector}`,
    "  and on (env, job, instance) (",
    "    trajetto_alert_evaluated_timestamp_seconds",
    "    == on (env) group_left ()",
    "    max by (env) (trajetto_alert_evaluated_timestamp_seconds)",
    "  )",
    "  and on (env, job, instance) (",
    `    time() - trajetto_alert_evaluated_timestamp_seconds < ${VERDICT_FRESH_SECONDS}`,
    "  )",
    ")",
  ].join("\n");
}

/**
 * The mirror of every code of ALERT_KINDS: the same reasons the
 * healthchecks.io ping carries, as alerts with history. The thresholds stay
 * in alert-rules.ts; the rule only reads the verdict, so the two can never
 * disagree on when a reason is active.
 */
function alertCodeRules(): AlertRule[] {
  return ALERT_KINDS.map((code) => ({
    alert: alertName(code),
    expr: `${verdictExpr(`{code="${code}"}`)} == 1`,
    for: "1m",
    severity: "page",
    source: "ops-heartbeat",
    summary: runbookTitle(code),
    runbook: runbookPath(code),
  }));
}

