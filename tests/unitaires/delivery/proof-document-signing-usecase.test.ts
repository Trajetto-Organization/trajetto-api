function makeContext(
  signing: ProofSigningService = unsignedSigning(),
  location: ProofLocationService = noLocationProviders(),
) {
  const users = new InMemoryUserRepository();
  users.user.push({
    id: USER,
    role: "BUSINESS_ADMIN",
    businessId: BUSINESS,
  } as User);

  const documents = new InMemoryProofDocumentRepository();
  documents.addSource(BUSINESS, source());

  const bucket = new Map<string, Buffer>();

  const uploads = {
    readObject: async (key: string) => bucket.get(key) ?? null,
    putObject: async (key: string, body: Buffer) => {
      bucket.set(key, body);
    },
    getFileUrl: async (key: string) => `https://bucket.exemplo/${key}`,
  };

  const build = (useSigning = signing) =>
    new GetProofDocumentUseCase(
      users,
      documents,
      uploads as never,
      useSigning,
      location,
    );

  const open = (regenerate?: boolean, useSigning = signing) =>
    build(useSigning).execute({
      userId: USER,
      businessId: BUSINESS,
      deliveryId: DELIVERY,
      regenerate,
    });

  return { documents, bucket, open };
}

describe("without a certificate", () => {
  it("stores an unsigned document in the new layout, with the reason recorded", async () => {
    const { documents, bucket, open } = makeContext();

    const result = await open();
    const [row] = documents.documents;

    expect(row).toMatchObject({
      layout_version: 2,
      signature_status: "UNSIGNED",
      unsigned_reason: "NO_CERTIFICATE",
      signature_profile: null,
      signer_name: null,
      signed_at: null,
    });
    expect(result.signingAvailable).toBe(false);

    const bytes = bucket.get(row.storage_key)!;

    expect(bytes.toString("latin1")).not.toContain("/ByteRange");
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(row.sha256);
  }, 60_000);
});

describe("with the platform certificate", () => {
  it("stores the SIGNED bytes, hashed after signing, and who signed them", async () => {
    const { documents, bucket, open } = makeContext(testCertificateSigning());

    const result = await open();
    const [row] = documents.documents;

    expect(row).toMatchObject({
      layout_version: 2,
      signature_status: "SIGNED",
      unsigned_reason: null,
      signature_profile: "PADES_AD_RB",
      signer_name: "TRAJETTO SISTEMAS TESTE LTDA",
      signer_cnpj: "11222333000181",
      cert_serial: "0a1b2c3d4e5f",
    });
    expect(row.signed_at).toBeInstanceOf(Date);
    expect(row.cert_not_after).toBeInstanceOf(Date);
    expect(result.signingAvailable).toBe(true);

    const bytes = bucket.get(row.storage_key)!;

    // The row's hash is of the final, signed file: what /verificar compares.
    expect(bytes.toString("latin1")).toMatch(/\/ByteRange \[0 \d+ \d+ \d+/);
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(row.sha256);
    expect(row.storage_key).toBe(
      `deliveryProofs/${DELIVERY}/${row.sha256}.pdf`,
    );
  }, 60_000);

  it("answers 503 PROOF_SIGNING_FAILED and stores nothing when signing fails", async () => {
    // A placeholder too small for the CMS: a real failure of the signer.
    const { documents, bucket, open } = makeContext(
      testCertificateSigning({ signatureLength: 64 }),
    );

    await expect(open()).rejects.toMatchObject({
      statusCode: 503,
      code: "PROOF_SIGNING_FAILED",
    });

    expect(documents.documents).toHaveLength(0);
    expect(bucket.size).toBe(0);
  }, 60_000);

  it("replaces the signature columns on a regeneration and keeps the token", async () => {
    const { documents, open } = makeContext(testCertificateSigning());

    await open();
    const token = documents.documents[0].verification_token;

    // The certificate was removed: the next version is honest about it.
    await open(true, unsignedSigning());

    expect(documents.documents).toHaveLength(1);
    expect(documents.documents[0]).toMatchObject({
      version: 2,
      verification_token: token,
      signature_status: "UNSIGNED",
      unsigned_reason: "NO_CERTIFICATE",
      signer_name: null,
      signer_cnpj: null,
      signed_at: null,
    });
  }, 60_000);
});

describe("the GPS address", () => {
  function geocoding() {
    const calls: string[] = [];
    const fetcher: GeocodeFetch = async (url) => {
      calls.push(url);
      return {
        status: 200,
        json: async () => ({
          address: {
            road: "Praça da Sé",
            house_number: "1",
            city: "São Paulo",
          },
        }),
      };
    };

    const location = new ProofLocationService({
      geocoder: {
        url: "https://geo.example",
        key: undefined,
        keyParam: "key",
        userAgent: "t",
        timeoutMs: 1000,
      },
      map: { template: undefined, attribution: undefined, timeoutMs: 100 },
      fetcher: fetcher as never,
    });

    return { calls, location };
  }

  it("is looked up on the first render, cached on the event, and not asked again on regeneration", async () => {
    const { calls, location } = geocoding();
    const { documents, open } = makeContext(unsignedSigning(), location);

    await open();

    const cached = documents.sources.get(DELIVERY)!.source.proof!;

    expect(cached.gps_address_source).toBe("PROVIDER");
    expect(cached.gps_address?.line).toBe("Praça da Sé, 1");
    expect(cached.gps_geocoded_at).toBeInstanceOf(Date);

    await open(true);

    expect(calls).toHaveLength(1);
  }, 60_000);

  it("is cached only on the owning company's event", async () => {
    const documents = new InMemoryProofDocumentRepository();
    documents.addSource(BUSINESS, source());

    await documents.saveGpsAddress(EVENT, OTHER, {
      gps_address: {
        line: "Outro lugar",
        district: null,
        city: null,
        state: null,
        cep: null,
      },
      gps_address_source: "PROVIDER",
      gps_geocoded_at: new Date(),
    });

    expect(
      documents.sources.get(DELIVERY)!.source.proof!.gps_address,
    ).toBeUndefined();
  });
});
