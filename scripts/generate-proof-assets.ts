/**
 * Regenerates src/shared/services/proof-assets.generated.ts from the
 * versioned PNG in assets/proof/ (decision 14.8, design §2).
 *
 * The receipt worker is its own bundle and the production image has no
 * guaranteed path to assets/, so the watermark travels embedded as base64.
 * tests/unitaires/delivery/proof-assets.test.ts fails when the two drift.
 *
 * To change the brand: replace assets/proof/trajetto-logo.png (transparent
 * PNG), update WATERMARK_SYMBOL_BOX below if the symbol moved inside the
 * frame, and run `npx tsx scripts/generate-proof-assets.ts`.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
const source = path.join(root, "assets", "proof", "trajetto-logo.png");
const target = path.join(
  root,
  "src",
  "shared",
  "services",
  "proof-assets.generated.ts",
);

/**
 * Where the symbol sits inside the 1024×1024 frame, in pixels — measured on
 * the non-transparent, non-white pixels of the PNG. The renderer centres the
 * symbol, not the frame, so the mostly empty frame does not shift the mark.
 */
const WATERMARK_SYMBOL_BOX = { x0: 194, y0: 381, x1: 810, y1: 696 };

const bytes = fs.readFileSync(source);
const sha256 = createHash("sha256").update(bytes).digest("hex");

const width = bytes.readUInt32BE(16);
const height = bytes.readUInt32BE(20);

const lines = bytes.toString("base64").match(/.{1,100}/g) ?? [];

const content = `// GENERATED by scripts/generate-proof-assets.ts — do not edit by hand.
// Source: assets/proof/trajetto-logo.png (sha256 ${sha256}).

/** The Trajetto symbol, drawn as the receipt's watermark. */
const TRAJETTO_WATERMARK_PNG = Buffer.from(
  [
${lines.map((line) => `    "${line}",`).join("\n")}
  ].join(""),
  "base64",
);

const TRAJETTO_WATERMARK_SHA256 = "${sha256}";

/** Frame size and the symbol's box inside it, in pixels. */
const TRAJETTO_WATERMARK_FRAME = { width: ${width}, height: ${height} } as const;
const TRAJETTO_WATERMARK_SYMBOL = ${JSON.stringify(WATERMARK_SYMBOL_BOX).replace(/"/g, "").replace(/,/g, ", ").replace(/:/g, ": ").replace("{", "{ ").replace("}", " }")} as const;

export {
  TRAJETTO_WATERMARK_FRAME,
  TRAJETTO_WATERMARK_PNG,
  TRAJETTO_WATERMARK_SHA256,
  TRAJETTO_WATERMARK_SYMBOL,
};
`;

fs.writeFileSync(target, content);

console.log(`proof-assets.generated.ts written (${bytes.length} bytes, sha256 ${sha256})`);
